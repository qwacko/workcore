import { readdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const root = new URL('../', import.meta.url);
const outDir = resolve(root.pathname, 'drizzle');
const metaDir = resolve(outDir, 'meta');
const journal = JSON.parse(await readFile(resolve(metaDir, '_journal.json'), 'utf8'));
const files = await readdir(outDir);
const migrations = {};
for (const entry of journal.entries) {
  const file = `${entry.tag}.sql`;
  if (!files.includes(file)) throw new Error(`Journal migration file missing: ${file}`);
  migrations[`m${String(entry.idx).padStart(4, '0')}`] = await readFile(resolve(outDir, file), 'utf8');
}
await writeFile(resolve(root.pathname, 'src/migrations.ts'), `// Generated by scripts/ingest-migrations.mjs. Do not edit.\nimport type { MigrationBundle } from '@workcore/core';\nexport default ${JSON.stringify({ journal, migrations }, null, 2)} as MigrationBundle;\n`);
console.log(`Ingested ${journal.entries.length} Drizzle migration(s).`);
